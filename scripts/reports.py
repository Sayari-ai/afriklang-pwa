"""Generate ATTRIBUTIONS.md + per-path review HTML pages from the ledger."""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from pipeline.ledger import Ledger


HTML_HEAD = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>{title}</title>
<style>
body{{font-family:system-ui,sans-serif;background:#111;color:#eee;margin:24px}}
h1{{font-size:24px;margin:0 0 16px}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:16px}}
.card{{background:#1d1d1d;border-radius:8px;padding:12px}}
.card img{{width:100%;height:180px;object-fit:cover;border-radius:6px;background:#000}}
.meta{{font-size:12px;color:#aaa;margin-top:6px;line-height:1.4}}
.meta b{{color:#fff}}
a{{color:#9cf}}
</style></head><body>
<h1>{title}</h1>
<div class="grid">
"""

HTML_FOOT = "</div></body></html>"


def write_review_html(ledger: Ledger, review_dir: Path) -> list[Path]:
    rows_by_path: dict[int, list[tuple[int, int, dict]]] = defaultdict(list)
    for pid, lid, qi, row in ledger.iter_done_rows():
        rows_by_path[pid].append((lid, qi, row))

    review_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for pid, items in sorted(rows_by_path.items()):
        items.sort(key=lambda t: (t[0], t[1]))
        path = review_dir / f"p{pid:02d}.html"
        chunks = [HTML_HEAD.format(title=f"Path {pid:02d} review")]
        for lid, qi, row in items:
            chunks.append(
                f'<div class="card">'
                f'<img src="{row.get("image_url","")}" alt="">'
                f'<div class="meta"><b>L{lid} q{qi}</b><br>'
                f'{row.get("provider","")} · {row.get("license","")}<br>'
                f'{row.get("photographer") or ""}<br>'
                f'<a href="{row.get("source_page_url","")}" target="_blank">source</a>'
                f"</div></div>"
            )
        chunks.append(HTML_FOOT)
        path.write_text("".join(chunks), "utf-8")
        written.append(path)
    return written


def write_attributions_md(ledger: Ledger, out_path: Path) -> Path:
    rows_by_path: dict[int, list[tuple[int, int, dict]]] = defaultdict(list)
    for pid, lid, qi, row in ledger.iter_done_rows():
        rows_by_path[pid].append((lid, qi, row))

    lines: list[str] = ["# Image attributions", ""]
    lines.append(
        "Auto-generated by `scripts/source_images.py`. One entry per image; grouped by path."
    )
    lines.append("")
    for pid, items in sorted(rows_by_path.items()):
        items.sort(key=lambda t: (t[0], t[1]))
        lines.append(f"## Path {pid:02d}")
        lines.append("")
        for lid, qi, row in items:
            photographer = row.get("photographer") or "Unknown"
            license_label = row.get("license") or ""
            license_url = row.get("license_url")
            page = row.get("source_page_url") or ""
            license_text = (
                f"[{license_label}]({license_url})" if license_url else license_label
            )
            lines.append(
                f"- L{lid} q{qi}: {photographer} via {row.get('provider','')} — "
                f"{license_text} — [source]({page})"
            )
        lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), "utf-8")
    return out_path
