// Builds deploy/campaigns-single-file.ts: the `campaigns` Edge Function as ONE file, for pasting
// into the Supabase dashboard editor (which cannot import from ../_shared).
//   node scripts/build-campaigns-single-file.mjs          write the file
//   node scripts/build-campaigns-single-file.mjs --check  fail if the committed file is stale
import { readFileSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const util = read("supabase/functions/_shared/util.ts");
const logic = read("supabase/functions/_shared/campaigns.ts");
const index = read("supabase/functions/campaigns/index.ts");

// Only the few helpers the function uses from util.ts.
const utilStart = util.indexOf("export const corsHeaders");
const utilEnd = util.indexOf("export function serviceClient");
if (utilStart < 0 || utilEnd < 0) throw new Error("util.ts changed shape: update this script");
const utilPart = util.slice(utilStart, utilEnd).replace(/^export /gm, "");

const strip = (src) => src.replace(/^import [\s\S]*?;\n/gm, "");
const indexBody = strip(index).replace(/^\/\/ POST[\s\S]*?\n\n/, "");

const out = `// GENERATED by scripts/build-campaigns-single-file.mjs from supabase/functions/{_shared,campaigns}.
// Do not edit here: change the sources and run the script again.
//
// One-file version of the \`campaigns\` Edge Function, for the Supabase dashboard editor
// (Edge Functions -> Deploy a new function -> Via Editor). Name the function exactly \`campaigns\`.
//
//   - Leave "Verify JWT" ON (the default): callers must be signed-in users.
//   - Secrets (Edge Functions -> Secrets): BRIDGE_SECRET (same value as PWA_BRIDGE_SECRET on the
//     dashboard) and DASHBOARD_URL (https origin of the dashboard, no path).
//   - Nothing from a request body is ever logged: it carries invitation tokens.

import { createClient } from "https://esm.sh/@supabase/supabase-js@2.45.0";

// ── helpers (from _shared/util.ts) ───────────────────────────────────────

${utilPart.trim()}

function serviceClient() {
  const url = Deno.env.get("SUPABASE_URL");
  const key = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
  if (!url || !key) throw new Error("SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY missing");
  return createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
}

// ── logic (from _shared/campaigns.ts) ────────────────────────────────────

${strip(logic).replace(/^export /gm, "").trim()}

// ── handler (from campaigns/index.ts) ────────────────────────────────────

${indexBody.trim()}
`;

const target = new URL("../deploy/campaigns-single-file.ts", import.meta.url);
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* missing */ }
  if (current !== out) { console.error("deploy/campaigns-single-file.ts is stale: run node scripts/build-campaigns-single-file.mjs"); process.exit(1); }
  console.log("up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${out.split("\n").length} lines`);
}
